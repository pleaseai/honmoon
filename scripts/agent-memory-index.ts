/**
 * Rebuild every `.claude/agent-memory/<agent>/MEMORY.md` index from the notes
 * beside it.
 *
 * The index is a pointer list — one line per note — that Claude Code loads into
 * a subagent's context so it can pick which note to open. Every line is already
 * derivable from the note it points at: the link text is that note's
 * frontmatter `name:`, the hook after the em dash is its `description:`.
 *
 * It used to be hand-appended and tracked in git, which cost two things (#129):
 *
 *   - Two PRs in flight that both recorded a memory for the *same* agent
 *     appended to the same line of the same file and collided. The correct
 *     resolution is always the union of all entries, which is not what the
 *     conflict hunk shows — a third party's entry can already be missing from
 *     both sides — so a careless resolve deletes a note's pointer silently.
 *   - The hook duplicated the note's own `description:`, so one claim lived in
 *     three places (note body, frontmatter, index line) and correcting one left
 *     two. Both copies have shipped a claim the other contradicted: the index
 *     lines for `project_flush_refusal_barrier_pg113` and
 *     `project_signed_body_framing_headers_83` each described a gap their own
 *     note said was closed (see the commit that folded the hooks into the
 *     descriptions, and the discussion on the issue).
 *
 * Deriving the file removes both classes: it is generated, git-ignored, and the
 * `description:` is the single source of the index text. The notes themselves
 * stay tracked — they are the memory; this file is only a table of contents.
 *
 * Usage:
 *   bun scripts/agent-memory-index.ts           # rewrite every index
 *   bun scripts/agent-memory-index.ts --check   # verify only, write nothing (CI)
 */
import { existsSync, lstatSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

/** Repository root, resolved from this file rather than the working directory. */
export const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url))

/** Directory holding one sub-directory of notes per agent, relative to the root. */
export const MEMORY_ROOT = '.claude/agent-memory'

/** Absolute path of {@link MEMORY_ROOT} — a hook or CI step can run from anywhere. */
export const MEMORY_DIR = join(REPO_ROOT, MEMORY_ROOT)

/** The index file inside each agent directory. Generated, never hand-edited. */
export const INDEX_NAME = 'MEMORY.md'

/**
 * Header written above the entries.
 *
 * Claude Code appends to `MEMORY.md` itself when an agent records a memory, so
 * the banner has to tell both a human and an agent that a hand-written line is
 * transient — it survives only until the next rebuild, and the durable place
 * for that text is the note's own `description:`.
 */
export const INDEX_BANNER = `<!-- Generated by scripts/agent-memory-index.ts from the \`name:\`/\`description:\`
     frontmatter of the notes in this directory (issue #129). Not tracked in git, and
     hand edits do not survive: to change a line, edit that note's \`description:\`.
     Rebuild with \`bun scripts/agent-memory-index.ts\`. -->`

/** One note reduced to what the index needs, plus anything wrong with it. */
export interface NoteEntry {
  /** File name of the note, relative to its agent directory. */
  file: string
  /** Frontmatter `name:`, falling back to the file stem. */
  name: string
  /** Frontmatter `description:`; empty when the note has none. */
  description: string
  /** Human-readable defects — a note is still indexed when it has some. */
  problems: string[]
}

const FRONTMATTER = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/
// Two separate reasons the value group is spelled `(\S.*)?` and not `(.*)`,
// both load-bearing and neither obvious:
//   - the `?` is what makes a bare `metadata:` capture `undefined` instead of
//     `''`, which is how `parseFrontmatter` below tells a nested-mapping opener
//     apart from a scalar whose value is empty. Verified: with `(.*)` the group
//     captures `''` for `metadata:` and the distinction is gone.
//   - `\S` keeps the value class disjoint from the `[ \t]*` before it, so the
//     two cannot match the same character and the match stays linear
//     (eslint `regexp/no-super-linear-backtracking`). It does *not* affect what
//     is captured — `[ \t]*` is greedy, so `(.*)?` captures the same text.
const TOP_LEVEL_KEY = /^([a-z][\w-]*):[ \t]*(\S.*)?$/i

/**
 * A YAML block-scalar header — `>` or `|`, with an optional explicit indent
 * (a single digit) and chomping indicator (`+`/`-`) in **either** order, which
 * is what the YAML block-header production allows: `>-`, `|+`, `>2`, `|2-`,
 * `>+2` are all legal.
 *
 * The value is carried by the indented lines that follow, so the header itself
 * must not become the value: `description: >` would otherwise index as the
 * literal `>` with the real text folded onto it. A header may carry a trailing
 * comment, the same allowance the quoted forms get — and for the same reason,
 * that failing to recognise the header does not fail loudly, it indexes the
 * header text as though the note had written it.
 */
const BLOCK_SCALAR = /^[|>](?:[1-9][+-]?|[+-][1-9]?)?(?:[ \t]+(?:#.*)?)?$/

/**
 * The YAML double-quoted escapes that stand for one character.
 *
 * Unescaping only `\"` and `\\` is not enough: in a double-quoted scalar every
 * one of these is the character, not the two letters, so leaving them alone
 * puts a literal `\n` in the index where the note said a space.
 */
const DOUBLE_QUOTED_ESCAPES: Record<string, string> = {
  '0': '\0',
  'a': '\x07',
  'b': '\b',
  't': '\t',
  'n': '\n',
  'v': '\v',
  'f': '\f',
  'r': '\r',
  'e': '\x1B',
  ' ': ' ',
  '"': '"',
  '/': '/',
  '\\': '\\',
  'N': '\x85',
  '_': '\xA0',
  'L': '\u2028',
  'P': '\u2029',
}

/**
 * Resolve the escape sequences of a YAML double-quoted scalar's body.
 *
 * An escape this cannot resolve is reported through `onInvalid` rather than
 * quietly kept as its two literal characters. The text is kept either way — a
 * guess would be worse — but the note has to be flagged, because a description
 * whose YAML is invalid is one where this reader and the reader that loads the
 * note into an agent's context can disagree. Two readers disagreeing about one
 * claim is the drift this index was derived to remove; it cannot be allowed
 * back in through the parser.
 */
function unescapeDoubleQuoted(body: string, onInvalid: (escape: string) => void): string {
  return body.replace(
    /\\(x[0-9A-Fa-f]{2}|u[0-9A-Fa-f]{4}|U[0-9A-Fa-f]{8}|[\s\S])/g,
    (match, escape: string) => {
      if (escape.length > 1) {
        // `\U` admits eight digits, which reach far past the last code point,
        // and `String.fromCodePoint` throws on those. A malformed note has to
        // come back as a reported problem, never as a crash that takes the
        // whole run — and every other note with it — down with it.
        const codePoint = Number.parseInt(escape.slice(1), 16)
        if (codePoint > 0x10FFFF) {
          onInvalid(match)
          return match
        }
        return String.fromCodePoint(codePoint)
      }

      const resolved = DOUBLE_QUOTED_ESCAPES[escape]
      if (resolved === undefined) {
        onInvalid(match)
        return match
      }
      return resolved
    },
  )
}

/**
 * Strip one layer of YAML quoting from a scalar.
 *
 * The memory tool writes plain scalars, but a `description:` containing `": "`
 * has to be quoted to stay valid YAML, so both forms must round-trip.
 */
/**
 * YAML 1.1's `int` and `float` resolvers, transcribed from its type registry.
 *
 * They are wider than 1.2's core schema in two ways worth naming: every digit
 * run admits `_` as a separator, and a colon-separated value is base 60. So a
 * 1.1 reader makes `1_000` the number 1000 and `12:00` the number 720 where a
 * 1.2 one leaves both as text — the same disagreement `1e3` has, in the other
 * direction, and the same reason to report rather than pick a side.
 */
const YAML_11_INT = String.raw`[-+]?0b[01_]+|[-+]?0[0-7_]+|[-+]?(?:0|[1-9][\d_]*)|[-+]?0x[\da-f_]+|[-+]?[1-9][\d_]*(?::[0-5]?\d)+`
const YAML_11_FLOAT = String.raw`[-+]?\d[\d_]*\.[\d_]*(?:e[-+]\d+)?|\.\d[\d_]*(?:e[-+]\d+)?|[-+]?\d[\d_]*(?::[0-5]?\d)+\.[\d_]*|[-+]?\.(?:inf|nan)`

/**
 * YAML 1.1's `timestamp` resolver, which 1.2's core schema does not carry.
 *
 * A description that is a bare date is a `Date` to a 1.1 reader and text to a
 * 1.2 one, so it is ambiguous for the same reason the numbers above are.
 */
const YAML_11_TIMESTAMP = String.raw`\d{4}-\d{2}-\d{2}|\d{4}-\d{1,2}-\d{1,2}(?:t|[ \t]+)\d{1,2}:\d{2}:\d{2}(?:\.\d*)?(?:[ \t]*(?:z|[-+]\d{1,2}(?::\d{2})?))?`

/**
 * The numbers 1.2's core schema resolves and 1.1 does not: an exponent needs
 * neither a fraction nor a signed power, a leading zero does not mean octal,
 * and octal is written with an `0o` prefix instead.
 */
const YAML_12_NUMBER = String.raw`[-+]?0o[0-7]+|[-+]?\d+(?:\.\d*)?(?:e[-+]?\d+)?|[-+]?\.\d+(?:e[-+]?\d+)?`

/**
 * A plain scalar YAML resolves to something that is not a string.
 *
 * `description: null` is not the word "null", it is the *absence* of a value,
 * and `true` and `42` are a boolean and an integer. Storing the source spelling
 * made a note with no summary advertise `null` as its summary. Only a whole
 * value matches — a description reading `42 ways to fail` is text and stays
 * text — and only a plain one, since `"null"` is genuinely the string.
 */
const NON_STRING_SCALAR = new RegExp(`^(?:${[
  String.raw`~|null|true|false|yes|no|on|off`,
  YAML_11_INT,
  YAML_11_FLOAT,
  YAML_12_NUMBER,
  YAML_11_TIMESTAMP,
].join('|')})$`, 'i')

/** A leading YAML node indicator, which makes the rest a decoration, not text. */
const NODE_INDICATOR = /^([&*!])/
const INDICATOR_NAMES: Record<string, string> = { '&': 'anchor', '*': 'alias', '!': 'tag' }

/**
 * A whole double- or single-quoted scalar, with the body captured.
 *
 * Matched as a unit rather than tested with `startsWith`/`endsWith`, which
 * cannot see either end of the interesting cases: `"unfinished \"` *ends* with
 * a quote that is escaped and therefore closes nothing, while a valid
 * `"text" # note` does not end with one at all. Consuming the body as "not the
 * quote, or an escape and whatever it escapes" settles both, and the trailing
 * group is YAML's inline comment — which is only a comment out here, never
 * inside the quotes, where these descriptions keep their issue references.
 */
const DOUBLE_QUOTED = /^"((?:[^"\\]|\\[\s\S])*)"(?:\s+#.*)?$/
const SINGLE_QUOTED = /^'((?:[^']|'')*)'(?:\s+#.*)?$/

function unquote(value: string, onInvalid: (problem: string) => void): string {
  // A plain scalar cannot begin with a quote, so one that does is a quoted
  // scalar, and one that does not parse as a whole quoted scalar is a note
  // whose YAML does not load. Returning it raw would list it as though it were
  // fine.
  if (value.startsWith('"')) {
    const body = DOUBLE_QUOTED.exec(value)?.[1]
    if (body === undefined) {
      onInvalid('opens with " and never closes it, so the frontmatter is not valid YAML')
      return value
    }
    return unescapeDoubleQuoted(body, onInvalid)
  }

  if (value.startsWith('\'')) {
    const body = SINGLE_QUOTED.exec(value)?.[1]
    if (body === undefined) {
      onInvalid('opens with \' and never closes it, so the frontmatter is not valid YAML')
      return value
    }
    return body.replace(/''/g, '\'')
  }

  // `&`, `*` and `!` are node indicators, not text: a plain scalar cannot begin
  // with one, so a value that does is an anchor, an alias or a tag. Keeping the
  // decoration as the index text would put `&summary concrete summary` in the
  // index where the note's value is `concrete summary`, and an alias cannot be
  // resolved here at all without carrying an anchor table — which is a YAML
  // parser, and this deliberately is not one. Reported rather than guessed at.
  const indicator = NODE_INDICATOR.exec(value)?.[1]
  if (indicator !== undefined) {
    onInvalid(`starts with the YAML ${INDICATOR_NAMES[indicator]} indicator \`${indicator}\`, which this reader does not resolve — write the value as a plain, quoted or block scalar`)
    return value
  }

  return value
}

/** What a note's frontmatter block yields: its scalars, and why any is suspect. */
export interface Frontmatter {
  scalars: Record<string, string | undefined>
  problems: string[]
}

/**
 * Read the top-level scalars out of a note's frontmatter block.
 *
 * Deliberately not a YAML parser: it needs `name` and `description` and nothing
 * else. A key whose value is empty (`metadata:`) opens a nested mapping whose
 * indented lines are skipped; a key whose value is not empty absorbs following
 * indented lines as a folded continuation, which is how a long `description:`
 * wraps.
 */
export function parseFrontmatter(text: string): Frontmatter {
  const block = FRONTMATTER.exec(text)
  if (!block) {
    return { scalars: {}, problems: [] }
  }

  const problems: string[] = []
  const scalars: Record<string, string | undefined> = {}
  const blockScalars = new Set<string>()
  let key: string | null = null

  for (const line of block[1].split(/\r?\n/)) {
    const top = TOP_LEVEL_KEY.exec(line)
    if (top) {
      const [, name, value] = top
      // `key: # text` is a key with a *comment*, and YAML gives it a null value.
      // Capturing the comment as the value is how `description: # write this
      // later` reached an index as though it were the summary, when what the
      // note actually has is no description at all.
      key = value === undefined || value.startsWith('#') ? null : name
      if (key) {
        // A block-scalar header opens a value the following indented lines
        // carry, so start empty and let the continuation branch fill it. Both
        // `>` and `|` end up folded onto one line, which is all an index line
        // can be.
        if (BLOCK_SCALAR.test(value)) {
          scalars[key] = ''
          blockScalars.add(key)
        }
        else {
          scalars[key] = value
        }
      }
      continue
    }
    // Only an *indented* line continues the previous non-empty scalar — that is
    // what folding means in YAML, and it is also what keeps a column-0 comment
    // line out of the value above it. An indented `#` is left alone on purpose:
    // inside a folded scalar it is literal text, and these descriptions are full
    // of issue references that a comment-stripping parser would eat.
    if (key && /^[ \t]/.test(line) && line.trim() !== '') {
      const soFar = scalars[key] ?? ''
      // Inside a double-quoted scalar a trailing backslash escapes the line
      // break itself: YAML drops the break *and* the indentation and joins with
      // nothing, where every other continuation joins with a space. Folding
      // both the same way turned `"one\` + `two"` into `one two` — and then the
      // decoder read the `\ ` it had just created as an escaped space, so the
      // index said something the note never did. The count has to be odd: a
      // `\\` at the end is an escaped backslash, not an escaped break.
      if (soFar.startsWith('"') && /(?:^|[^\\])(?:\\\\)*\\$/.test(soFar)) {
        scalars[key] = `${soFar.slice(0, -1)}${line.trim()}`
      }
      else {
        scalars[key] = `${soFar} ${line.trim()}`
      }
    }
  }

  // Collapsed after unquoting, not before, and that order is load-bearing: an
  // index entry is one line of a markdown list, and a double-quoted `\n` only
  // becomes a newline once `unquote` has decoded it. Folding here means no
  // description can split its own list item, whatever notation wrote it.
  for (const [name, value] of Object.entries(scalars)) {
    const raw = (value ?? '').trim()

    // In a plain scalar — and only there — whitespace followed by `#` starts a
    // comment, so YAML reads `fixed in PR #155, so do X` as `fixed in PR`. This
    // reader keeps the whole line, and that difference is the drift the derived
    // index exists to end: the note would say one thing here and another to the
    // reader that loads it. Reported rather than truncated, because the text
    // after the `#` is what the author meant; quoting the value keeps it.
    const plain = !blockScalars.has(name) && !raw.startsWith('"') && !raw.startsWith('\'')
    if (plain && /[ \t]#/.test(raw)) {
      problems.push(`\`${name}:\` is unquoted and contains \` #\`, which YAML reads as the start of a comment — quote the value so it survives`)
    }

    // `[summary]` is a sequence and `{summary: text}` a mapping — valid YAML,
    // and not a summary. Kept with the scalar checks because the failure is the
    // same one: the index would advertise the source spelling as the text.
    if (plain && (raw.startsWith('[') || raw.startsWith('{'))) {
      problems.push(`\`${name}:\` is a flow ${raw.startsWith('[') ? 'sequence' : 'mapping'}, not text — quote it if the brackets are part of the summary`)
    }

    if (plain && NON_STRING_SCALAR.test(raw)) {
      problems.push(`\`${name}:\` is \`${raw}\`, which YAML resolves to a ${raw === '~' || /^null$/i.test(raw) ? 'null' : 'non-string'} rather than text — quote it if the value really is that word`)
    }

    scalars[name] = unquote(raw, escape =>
      problems.push(`\`${name}:\` is double-quoted and holds \`${escape}\`, which YAML does not define — this reader keeps it literally, the reader that loads the note may not`))
      .replace(/\s+/g, ' ')
      .trim()
  }

  return { scalars, problems }
}

/**
 * Escape the characters that would end a markdown link label early.
 *
 * `name:` is free text an agent wrote, and a `]` in it would truncate the
 * pointer line into something that no longer resolves to the note. Only the
 * label needs this: the `description:` that follows sits outside any link
 * construct, where a bare parenthesis is just a parenthesis.
 */
function escapeLabel(text: string): string {
  return text.replace(/([[\]\\])/g, '\\$1')
}

const ENCODER = new TextEncoder()

/** File-name characters a markdown link destination can carry as themselves. */
const UNRESERVED = /[^\w.~-]/gu

/**
 * Render a file name as a markdown link destination.
 *
 * **Everything outside `UNRESERVED` is encoded, rather than a list of the
 * characters known to break.** That list was tried first and leaked three
 * times: `(` and whitespace end the destination in the *markdown* parse, then
 * `#`, `?` and `%` survive that and carry meaning in the *URL*, then `:` makes
 * `review:notes.md` read as a URI scheme, then `\` resolves as a path
 * separator. Each was a true finding against an enumeration that could only
 * ever be as complete as the last person to think about it. Naming the safe
 * characters instead — and a file name is under no obligation to hold only
 * those — makes the set closed: an unforeseen character is encoded by default,
 * which is inert, instead of emitted raw, which is a link to the wrong file.
 *
 * Percent-encoding is defined over UTF-8 *bytes*, so the encoder runs over
 * bytes, not JS characters: a non-breaking space is one character and two
 * bytes, and `%A0` would not be the path. The `u` flag is part of the same
 * point at the other end of the range — without it the match is per UTF-16
 * code unit, so an astral name like `a😀b.md` arrives as two lone surrogates
 * and each encodes to the replacement character rather than to the emoji. (`encodeURIComponent` is not this
 * function: it leaves `(`, `)` and `!*'` unescaped, and the first two are
 * exactly what ends a bare markdown destination.)
 */
function linkTarget(file: string): string {
  return file.replace(UNRESERVED, character =>
    Array.from(ENCODER.encode(character), byte =>
      `%${byte.toString(16).toUpperCase().padStart(2, '0')}`).join(''))
}

/** Reduce one note file to its index entry. */
export function noteEntry(file: string, text: string): NoteEntry {
  const { scalars, problems } = parseFrontmatter(text)

  if (!FRONTMATTER.test(text)) {
    problems.push('has no `---` frontmatter block')
  }
  else if (!scalars.name) {
    problems.push('frontmatter has no `name:`')
  }

  if (!scalars.description) {
    problems.push('frontmatter has no `description:` — it is the index text, so the note lists without one')
  }

  return {
    file,
    name: scalars.name || file.replace(/\.md$/, ''),
    description: scalars.description ?? '',
    problems,
  }
}

/**
 * Render the index for one agent.
 *
 * Sorted by file name so the output depends only on the set of notes, never on
 * the order they were written or the order the filesystem returns them.
 */
export function renderIndex(entries: NoteEntry[]): string {
  const lines = [...entries]
    .sort((a, b) => (a.file < b.file ? -1 : a.file > b.file ? 1 : 0))
    .map(entry => `- [${escapeLabel(entry.name)}](${linkTarget(entry.file)}) — ${
      entry.description || '(no description — add one to this note\'s frontmatter)'
    }`)

  return `${[INDEX_BANNER, '', ...lines].join('\n')}\n`
}

/** Agent directories under `root`, in a stable order. */
export function agentDirs(root: string): string[] {
  if (!existsSync(root)) {
    return []
  }
  return readdirSync(root, { withFileTypes: true })
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name)
    .sort()
}

/** Notes in one agent directory — every `.md` file except the index itself. */
export function readNotes(dir: string): NoteEntry[] {
  return readdirSync(dir, { withFileTypes: true })
    // Excluding directories rather than selecting regular files: a directory
    // named `*.md` would otherwise reach `readFileSync` as `EISDIR`, while
    // `isFile()` would quietly drop a symlinked note, which is a real note.
    .filter(entry => !entry.isDirectory() && entry.name.endsWith('.md') && entry.name !== INDEX_NAME)
    .map(entry => entry.name)
    .sort()
    .map(file => noteEntry(file, readFileSync(join(dir, file), 'utf8')))
}

/**
 * Index files that are still tracked by git.
 *
 * This is the invariant the fix rests on: an index that re-enters the index
 * (git's, that is) brings the whole conflict class back with it, and no other
 * check in the repo reads that file. So an empty result has to mean the
 * invariant was checked and holds, never that checking failed — see the spawn
 * below, which raises rather than answering `[]` on a git it could not run.
 */
export function trackedIndexFiles(cwd: string = REPO_ROOT): string[] {
  // Spawned the way `scripts/bump-version.ts` shells out to cargo, and checked
  // the same way — on the exit code. Only "not a git repository" may answer
  // `[]`: that is the value meaning *the invariant holds*, so a git that
  // failed for any other reason (missing binary, unreadable index, a sandbox
  // that blocks it) must raise rather than report an all-clear nobody
  // verified. A bare repository is not one of those reasons — `ls-files` there
  // exits 0 with no output, so it reaches the same `[]` down the success path.
  // `-z` is not a detail: without it git C-quotes any path holding a non-ASCII
  // character, a quote or a backslash, so `agent-mémoire/MEMORY.md` arrives as
  // `"agent-m\303\251moire/MEMORY.md"` and ends in `"` — the suffix filter
  // below would miss it and report the all-clear this function exists to earn.
  const listed = Bun.spawnSync(['git', 'ls-files', '-z', '--', MEMORY_ROOT], { cwd })
  if (!listed.success) {
    const stderr = listed.stderr.toString()
    if (/not a git repository/i.test(stderr)) {
      return []
    }
    throw new Error(`git ls-files failed (exit ${listed.exitCode}): ${stderr.trim()}`)
  }
  return listed.stdout.toString().split('\0').filter(path => path.endsWith(`/${INDEX_NAME}`))
}

interface Result {
  /** Indexes whose on-disk content differed from the generated content. */
  written: string[]
  /** `<agent>/<note>: <problem>` for every note defect found. */
  problems: string[]
  /**
   * Reasons an index could not be written at all.
   *
   * Kept apart from `problems` because the two mean opposite things to a
   * caller: a note defect leaves a complete index with one placeholder line in
   * it, while anything here leaves that agent with no index. Folding them
   * together is what made `EXIT_PROBLEMS` claim more than it could keep.
   */
  refusals: string[]
}

/** Rebuild (or, with `check`, only inspect) every index under `root`. */
export function rebuild(root: string, options: { check?: boolean } = {}): Result {
  const written: string[] = []
  const problems: string[] = []
  const refusals: string[] = []

  // Every index path is inspected before any of them is written. Doing it per
  // agent inside one loop meant an earlier agent's index was already on disk by
  // the time a later one was refused, so a run that reported "nothing was
  // written" had written — the same clause-vs-code gap, one scope out.
  const refusedAgents = new Set<string>()
  for (const agent of agentDirs(root)) {
    const indexPath = join(root, agent, INDEX_NAME)
    if (lstatSync(indexPath, { throwIfNoEntry: false })?.isSymbolicLink()) {
      refusals.push(`${agent}/${INDEX_NAME}: is a symlink; an index is generated in place, refusing to write through it`)
      refusedAgents.add(agent)
    }
  }
  // Not an early return: the notes are still read and their defects still
  // reported, so one invocation names everything it found rather than making
  // the refusal hide a malformed note that will fail the next run too. What a
  // refusal stops is the *writing*, below.
  const refused = refusals.length > 0

  for (const agent of agentDirs(root)) {
    const dir = join(root, agent)
    const notes = readNotes(dir)
    for (const note of notes) {
      for (const problem of note.problems) {
        problems.push(`${agent}/${note.file}: ${problem}`)
      }
    }

    // Its notes are read and reported like everyone else's; its index path is
    // not ours to read either — a dangling link `lstat`s fine and then throws
    // on open, which is the same trap `existsSync` set at the other end.
    if (refusedAgents.has(agent)) {
      continue
    }

    const indexPath = join(dir, INDEX_NAME)
    const rendered = renderIndex(notes)

    // `lstat` rather than `existsSync` throughout: `existsSync` follows a
    // symlink, so it cannot be used to detect one, and it answers false for a
    // dangling link — the case where the write would *create* the target. The
    // refusal pass above has already ruled every index path out or in.
    const current = lstatSync(indexPath, { throwIfNoEntry: false })
      ? readFileSync(indexPath, 'utf8')
      : null
    if (current === rendered) {
      continue
    }

    if (refused) {
      continue
    }

    written.push(indexPath)
    if (!options.check) {
      writeFileSync(indexPath, rendered)
    }
  }

  return { written, problems, refusals }
}

/**
 * The exit code for a run that wrote every index and then reported defects in
 * the notes behind them.
 *
 * This is the one failure a caller may reasonably carry on from, so it has to
 * be distinguishable from the two that follow: one exit code for all of them
 * makes `|| true` the only option — the swallow this script exists to argue
 * against. The other two are `EXIT_INVARIANT`, and 1 for a run that could not
 * happen at all, which an uncaught throw produces.
 */
export const EXIT_PROBLEMS = 2

/**
 * The exit code for a broken invariant — an index that is tracked by git
 * again, or one that cannot be written because a symlink stands where it goes.
 *
 * Separate from `EXIT_PROBLEMS` because **nothing was written**: the run stops
 * before rebuilding so the tree is left as found, which means a caller that
 * tolerates a malformed note must not tolerate this one and call the result an
 * index.
 */
export const EXIT_INVARIANT = 3

function report(problems: string[], code: number): number {
  console.error('agent-memory index problems:')
  for (const problem of problems) {
    console.error(`  - ${problem}`)
  }
  return code
}

/**
 * Returns the process exit code: `EXIT_INVARIANT` when an index is tracked
 * again or could not be written, `EXIT_PROBLEMS` when every index was written
 * but a note cannot supply its line, 0 when clean. `root` and `cwd` are defaulted
 * for the CLI and only passed by the tests, which need a checkout of their own.
 */
export function main(argv: string[], root: string = MEMORY_DIR, cwd: string = REPO_ROOT): number {
  const check = argv.includes('--check')

  // Checked *and acted on* before rebuilding, not after: `rebuild` writes, and
  // a run that ends in a non-zero exit has written by then. A tracked index is
  // a broken invariant, so the tree is left exactly as found and the run stops.
  const tracked = trackedIndexFiles(cwd)
  if (tracked.length > 0) {
    return report(tracked.map(trackedIndex =>
      `${trackedIndex} is tracked by git — it is generated (issue #129). `
      + `Run \`git rm --cached ${trackedIndex}\`.`), EXIT_INVARIANT)
  }

  const { written, problems, refusals } = rebuild(root, { check })

  // Refusals first, and at the invariant code: they mean an agent has no index,
  // which a caller tolerating a malformed note must not be told to carry on
  // from. Reported together so one run names everything it found.
  if (refusals.length > 0) {
    return report([...refusals, ...problems], EXIT_INVARIANT)
  }

  if (problems.length > 0) {
    return report(problems, EXIT_PROBLEMS)
  }

  if (check) {
    console.log(`agent-memory index: ${written.length} file(s) would be rewritten, no problems`)
  }
  else {
    console.log(`agent-memory index: rebuilt ${written.length} file(s)`)
  }

  return 0
}

if (import.meta.main) {
  process.exit(main(process.argv.slice(2)))
}
